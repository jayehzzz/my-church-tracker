vi.mock('svelte/transition', () => ({ fade: () => ({}), fly: () => ({}), scale: () => ({}) }));
vi.mock('$lib/components/layout/DashboardLayout.svelte', async () => ({ default: (await import('../pipeline/TestLayout.svelte')).default }));
vi.mock('$lib/convex.js', () => ({ isDemoMode: () => false, getConvexHttpClient: () => null, getConvexClient: async () => null }));
vi.mock('$lib/auth/session.js', () => ({ session: writable({ status: 'authenticated', user: { id: 'reporter', role: 'owner', canViewConfidential: true } }) }));
vi.mock('$lib/stores/filterStore.js', () => ({ dateRange: writable({ label: 'July–September', startDate: '2026-07-01', endDate: '2026-09-30' }) }));
vi.mock('$lib/services/peopleService.js', () => ({ getAll: async () => ({ data: [], error: null }), formatJourneyStatus: () => 'Member' }));
vi.mock('$lib/services/evangelismService.js', () => ({ getAll: async () => ({ data: [{ id: 'old', first_name: 'Early', contact_date: '2026-07-04' }, { id: 'joined', first_name: 'Joined', contact_date: '2026-09-09', member_status: 'member' }], error: null }) }));
